####### Write a program that transforms a numerical grade to a letter grade (1 should display “A”)

A = 1
B = 2
C = 3
D = 4
E = 5

num = int(input("Enter a number 1-5: "))

if(num == 1):
    print("1 is A")

elif(num == 2):
    print("2 is B")

elif(num == 3):
    print("3 is C")

elif(num == 4):
    print("4 is D")

elif(num == 5):
    print("5 is E")

else:
    print("Enter valid value")

